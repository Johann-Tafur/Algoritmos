package com.ejercios;

//Ejercicio 13

//Calcular la suma de los primeros 100 números naturales.


public class Ejercicio13 {
    
    public static void main(String[] args){

        int Suma = 0;

        for (int i = 1; i <= 100; i++){

            Suma += i;
            
        }

        System.out.print(Suma);

    }

}
